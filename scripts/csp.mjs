import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export function scriptHashes(html) {
  const hashes = new Set();
  for (const [, attributes, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    if (/\bsrc\s*=/i.test(attributes) || !body.trim()) continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
  return [...hashes].sort();
}

export function protectHtml(html) {
  const hashes = scriptHashes(html);
  const scriptPolicy = `script-src 'self' ${hashes.join(' ')}; script-src-attr 'none'`;
  if (/<head\b[^>]*>/i.test(html)) {
    // The meta policy also protects fallback 404s and aliases served under another URL.
    // frame-ancestors remains in the HTTP header, where browsers support it.
    html = html.replace(/<head\b[^>]*>/i, head => `${head}<meta http-equiv="Content-Security-Policy" content="${scriptPolicy}"/>`);
  } else if (hashes.length) {
    throw new Error('Inline scripts found in a document without a head element.');
  }
  // Plain Google verification files intentionally remain byte-for-byte unchanged.
  return { html, hashes };
}

export function htmlRoutes(relativeFile) {
  const file = relativeFile.split(path.sep).join('/');
  if (file === 'index.html') return ['/', '/index.html'];
  if (file.endsWith('/index.html')) {
    const route = `/${file.slice(0, -'/index.html'.length)}`;
    return [route, `${route}/`, `/${file}`];
  }
  return [`/${file}`, `/${file.slice(0, -'.html'.length)}`];
}

const resourcePolicy = "style-src 'self' 'unsafe-inline'; img-src 'self' blob: data:; worker-src 'self' blob:; connect-src 'self'; font-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'none'; form-action 'none'";

export async function generateCsp(directory = 'out') {
  const root = path.resolve(directory);
  const routeHashes = new Map();
  async function visit(folder) {
    for (const entry of await readdir(folder, { withFileTypes: true })) {
      const target = path.join(folder, entry.name);
      if (entry.isDirectory()) await visit(target);
      else if (entry.name.endsWith('.html')) {
        const source = await readFile(target, 'utf8');
        if (/http-equiv=["']Content-Security-Policy["']/i.test(source)) throw new Error('CSP generation must run once on a fresh static export.');
        const protectedPage = protectHtml(source);
        await writeFile(target, protectedPage.html);
        for (const route of htmlRoutes(path.relative(root, target))) {
          if (!routeHashes.has(route)) routeHashes.set(route, new Set());
          for (const hash of protectedPage.hashes) routeHashes.get(route).add(hash);
        }
      }
    }
  }
  await visit(root);
  if (!routeHashes.size) throw new Error('No static HTML found for CSP generation.');
  // Global policy has no default/script directive: matching page policies supply it.
  // Separate comma-joined policies are intersected by the browser, never overridden.
  let headers = await readFile(path.join(root, '_headers'), 'utf8');
  if (/script-src\s+[^;\n]*'unsafe-inline'/.test(headers)) throw new Error('Remove the broad inline script policy before generating CSP.');
  headers += '\n# Generated by scripts/csp.mjs from this exact export.\n';
  for (const [route, hashes] of [...routeHashes.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const scriptPolicy = `script-src 'self' ${[...hashes].sort().join(' ')}; script-src-attr 'none'`;
    headers += `${route}\n  Content-Security-Policy: default-src 'self'; ${scriptPolicy}; ${resourcePolicy}\n\n`;
  }
  const lines = headers.split(/\r?\n/);
  const rules = lines.filter(line => line && !/^\s|^#/.test(line)).length;
  if (rules > 100 || lines.some(line => line.length > 2000)) throw new Error('Generated CSP exceeds Cloudflare Pages header limits.');
  await writeFile(path.join(root, '_headers'), headers);
  return { routes: routeHashes.size, maxHeaderLine: Math.max(...lines.map(line => line.length)) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  console.log('Static CSP generated:', await generateCsp());
}
